-- ============================================================================
-- Bulgarian names for exercises and recipes
-- ============================================================================
-- The exercise library was 25 of 40 translated and none of it was ever shown -
-- the workout screens read `exercises.name`. Both halves of that are fixed:
-- the remaining 15 are here, and migration 0023 made the screens read the
-- translation.
--
-- Recipes had no translations at all. Names carry what the dish IS, so they
-- are translated as dishes rather than word for word: "Chicken, rice and
-- broccoli" is "Пиле с ориз и броколи", not a transliteration.
--
-- Instructions are translated too. A recipe whose name is Bulgarian and whose
-- method is English is worse than one that is honestly English throughout -
-- it looks finished and is not.
-- ============================================================================

