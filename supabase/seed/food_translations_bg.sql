-- `food_aliases` makes a food FINDABLE in Bulgarian. This makes it READABLE:
-- the diary, the portion picker and the search list all show `foods.name`,
-- which is English, so a Bulgarian user who searched "кюфте" and logged it
-- then watched "Kyufte (grilled meatball)" appear in their day.
--
-- Not derived from the aliases. An alias is a search term and drops the
-- qualifiers on purpose - "кайма" has to match both minces - but a diary needs
-- to tell 5% from 15%, and raw from cooked. Two entries that both read "кайма"
-- are worse than two that read English.
--
-- Foods are joined by id suffix rather than repeating the full uuid on every
-- line. A suffix that matches nothing inserts nothing, which is why the pgTAP
-- suite asserts that every food ends up with a Bulgarian name rather than
-- trusting this file to be complete.
-- ============================================================================

